// Regenerates CONTENT-TODO.md: every "OWNER:" note in src/, config values that are still
// placeholders, and every photo slot that still needs a real image.
// Run with: npm run content-todo
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const src = path.join(root, "src");

function walk(dir, out = []) {
  for (const name of readdirSync(dir)) {
    const full = path.join(dir, name);
    if (statSync(full).isDirectory()) walk(full, out);
    else if (/\.(ts|tsx)$/.test(name)) out.push(full);
  }
  return out;
}

const rel = (file) => path.relative(root, file).replace(/\\/g, "/");
const files = walk(src).sort();

// 1. OWNER notes
const notes = [];
for (const file of files) {
  readFileSync(file, "utf8")
    .split(/\r?\n/)
    .forEach((line, i) => {
      const match = line.match(/OWNER:\s*(.+?)\s*(\*\/\s*\}?)?$/);
      if (match) notes.push({ file: rel(file), line: i + 1, text: match[1].replace(/\s*\*\/\s*\}?$/, "") });
    });
}

// Notes that must be resolved before the site goes live.
const BLOCKER = /offered before launch|needs local details|legal professional|verify neighborhood names and ZIP/i;
const blockers = notes.filter((n) => BLOCKER.test(n.text));
const others = notes.filter((n) => !BLOCKER.test(n.text));

// 2. Config placeholders (same rule as the dev warning banner). Node strips the TS types on import.
const { siteConfig } = await import(new URL("../src/config/site.ts", import.meta.url));
const placeholders = [];
(function find(value, keyPath) {
  if (typeof value === "string") {
    if (/\[[A-Z0-9_]+\]/.test(value)) placeholders.push(`${keyPath}: ${value}`);
  } else if (value && typeof value === "object") {
    for (const [key, child] of Object.entries(value)) find(child, keyPath ? `${keyPath}.${key}` : key);
  }
})(siteConfig, "");

// 3. Photo slots
const photos = new Map();
for (const file of files) {
  const source = readFileSync(file, "utf8");
  for (const m of source.matchAll(/file:\s*"([^"]+\.(?:webp|jpg|jpeg|png|avif))",\s*(?:\n\s*)?alt:\s*"([^"]+)"/g)) {
    if (!photos.has(m[1])) photos.set(m[1], { alt: m[2], file: rel(file) });
  }
}
const missingPhotos = [...photos].filter(([name]) => !existsSync(path.join(root, "public", "images", name)));

const groupByFile = (items) => {
  const groups = new Map();
  for (const n of items) (groups.get(n.file) ?? groups.set(n.file, []).get(n.file)).push(n);
  return [...groups].map(([file, list]) => `### ${file}\n\n${list.map((n) => `- [ ] Line ${n.line}: ${n.text}`).join("\n")}`).join("\n\n");
};

const md = `# Content To-Do

Generated by \`npm run content-todo\`. Re-run it after making changes; this file is overwritten each time.

**Summary:** ${blockers.length} launch blockers · ${others.length} other owner notes · ${placeholders.length} config placeholders · ${missingPhotos.length} photos still needed

## 1. Must fix before launch

These affect what the site claims publicly. Each must be confirmed, corrected, or the related page unpublished (\`published: false\`).

${blockers.length ? groupByFile(blockers) : "_None._"}

## 2. Site details still missing in \`src/config/site.ts\`

Anything still a placeholder is hidden on the live site, so the matching phone buttons, footer disclaimer, schema fields, and links won't appear until it's filled in.

${placeholders.length ? placeholders.map((p) => `- [ ] \`${p}\``).join("\n") : "_All filled in._"}

Also review: \`hours\` (when calls are answered) and \`social\` links. The site follows Ringba pay-per-call rules: no contact forms, no prices or cost content, no reviews or ratings, no "our team" or licensed/insured claims, and the disclaimer in every footer.

## 3. Claims and details to confirm

Each note marks a sentence the business owner must stand behind. Edit or delete the sentence if it isn't accurate, then remove the \`// OWNER:\` comment.

${groupByFile(others)}

## 4. Photos needed

Save each photo in \`public/images/\` with exactly this file name. It appears on the site automatically; until then the slot is hidden on the live site.

| File name | What it should show | Used in |
|---|---|---|
${missingPhotos.map(([name, info]) => `| \`${name}\` | ${info.alt} | ${info.file} |`).join("\n")}

## 5. Ongoing

- [ ] Have the Privacy Policy and Terms of Service reviewed by a legal professional.
- [ ] Set the Ringba tracking number and disclaimer in \`src/config/site.ts\`, then place a test call.
`;

writeFileSync(path.join(root, "CONTENT-TODO.md"), md);
console.log(
  `CONTENT-TODO.md written: ${blockers.length} blockers, ${others.length} notes, ${placeholders.length} placeholders, ${missingPhotos.length} photos.`,
);
